      var pick = document.createElement('input'); pick.type = 'color'; pick.value = get() || '#000000';
      var hex = document.createElement('input'); hex.type = 'text'; hex.value = get() || '';
      hex.className = 'swatch__hex'; hex.spellcheck = false;
