/* METUPUK — social templates
   ---------------------------------------------------------------------------
   Draws finished posts on a canvas, at the exact pixel size each platform
   wants, from the site's own tokens.

   Canvas rather than a screenshot of styled HTML. Turning a DOM node into an
   image means serialising it into an SVG foreignObject, and a webfont does not
   survive that trip — the export comes back in Times while the preview looked
   right. Drawing directly means the pixels downloaded are the pixels shown,
   and that a 1080x1080 post is 1080x1080 rather than whatever the screen was.

   Nothing here decides what the brand looks like. Colours come from
   a brand file under /social/brands/. That file is the whole contract: the
   colours by the job they do, the type, the marks, which templates exist, what
   their fields are called and open with, and the picture libraries they may
   draw from. The studio can draw nothing that is not in it.
   METUPUK's is generated by the build, out of :root in site.css and the same
   content the site is built from, so a brand colour changed in the stylesheet
   reaches the next post made here. Others can simply be written. Load one with
   ?brand=<id>. */
(function () {
  'use strict';

  var SIZES = {
    square: { w: 1080, h: 1080, label: 'Square', note: 'Instagram and Facebook feed' },
    story:  { w: 1080, h: 1920, label: 'Story',  note: 'Instagram and Facebook stories' },
    wide:   { w: 1200, h: 675,  label: 'Wide',   note: 'X, and shared link previews' }
  };
  /* Which templates exist, what they are called, what they open with and which
     picture library they draw from all arrive in the brand file. Nothing about
     any one organisation is written here. */
  function templates() { return (brand && brand.templates) || []; }
  function template(key) {
    return templates().filter(function (t) { return t.key === key; })[0] || { key: key, labels: {}, defaults: {} };
  }
  function label(key, field, fallback) {
    var t = template(key);
    return (t.labels && t.labels[field]) || fallback;
  }

  var canvas = document.getElementById('art');
  var ctx = canvas.getContext('2d');
  var statusEl = document.getElementById('status');
  var dimsEl = document.getElementById('dims');

  var brand = null;
  var images = {};
  var state = { template: '', size: 'square', ground: '', tag: '', fields: {} };

  var DISPLAY = 'system-ui,sans-serif';
  var BODY = 'system-ui,sans-serif';
  var DUOTONE = 'grayscale(1)';

  /* Every colour the templates use, named by the job it does rather than by
     what it looks like. A brand supplies "the colour of the figure", not
     "pink" — which is the only reason a second brand can be green. */
  function tok(role, fallback) {
    return (brand && brand.colour && brand.colour[role]) || fallback;
  }
  function grounds() {
    var list = (brand && brand.grounds) || [];
    var pick = list.filter(function (x) { return x.key === state.ground; })[0] || list[0];
    return pick ? [pick.from, pick.to] : ['#1c0310', '#2b0519'];
  }

  function lines(g, text, maxW) {
    var words = String(text || '').split(/\s+/).filter(Boolean);
    var out = [], line = '';
    for (var i = 0; i < words.length; i++) {
      var next = line ? line + ' ' + words[i] : words[i];
      if (g.measureText(next).width > maxW && line) { out.push(line); line = words[i]; }
      else line = next;
    }
    if (line) out.push(line);
    return out;
  }

  /* Shrink until it fits the box it was given. A headline nobody can read
     because it ran off the bottom is worse than one set a size smaller. */
  function fit(g, text, maxW, maxH, weight, family, start, min, lh) {
    var size = start;
    while (size > min) {
      g.font = weight + ' ' + size + 'px ' + family;
      var ls = lines(g, text, maxW);
      if (ls.length * size * lh <= maxH) {
        return { size: size, lines: ls, lh: lh, weight: weight, family: family };
      }
      size -= Math.max(1, Math.round(size * 0.04));
    }
    g.font = weight + ' ' + min + 'px ' + family;
    return { size: min, lines: lines(g, text, maxW), lh: lh, weight: weight, family: family };
  }

  function draw(g, block, x, y, colour) {
    g.fillStyle = colour;
    g.font = block.weight + ' ' + block.size + 'px ' + block.family;
    for (var i = 0; i < block.lines.length; i++) {
      g.fillText(block.lines[i], x, y + i * block.size * block.lh);
    }
    return y + block.lines.length * block.size * block.lh;
  }

  function load(src) {
    if (!src) return Promise.resolve(null);
    if (images[src]) return Promise.resolve(images[src]);
    return new Promise(function (resolve) {
      var img = new Image();
      img.onload = function () { images[src] = img; resolve(img); };
      img.onerror = function () { resolve(null); };
      img.src = src;
    });
  }

  /* Fill a box without squashing anybody. */
  function cover(g, img, x, y, w, h) {
    var r = Math.max(w / img.naturalWidth, h / img.naturalHeight);
    var dw = img.naturalWidth * r, dh = img.naturalHeight * r;
    g.drawImage(img, x + (w - dw) / 2, y + (h - dh) / 2, dw, dh);
  }

  function photo(g, img, x, y, w, h, duo) {
    g.save();
    g.beginPath(); g.rect(x, y, w, h); g.clip();
    if (duo && 'filter' in g) g.filter = DUOTONE;
    cover(g, img, x, y, w, h);
    g.filter = 'none';
    g.restore();
  }

  function scrim(g, x, y, w, h, from, to) {
    var grad = g.createLinearGradient(0, y, 0, y + h);
    grad.addColorStop(0, from); grad.addColorStop(1, to);
    g.fillStyle = grad; g.fillRect(x, y, w, h);
  }

  /* Every post signs itself. The mark, the name, the campaign's tag — so a
     picture that ends up screenshotted and reshared still says who it is. */
  function footer(g, S, u, pad, mark) {
    var base = S.h - pad;
    var markW = 0;
    /* A brand may not have a badge — Fen & Furrow does not — so the wordmark
       carries the signature on its own and the row simply starts further left. */
    if (mark) {
      var d = Math.round(58 * u);
      g.save();
      g.beginPath(); g.arc(pad + d / 2, base - d / 2, d / 2, 0, Math.PI * 2); g.closePath();
      g.fillStyle = '#fff'; g.fill(); g.clip();
      cover(ctx, mark, pad, base - d, d, d);
      g.restore();
      markW = d + Math.round(16 * u);
    }
    g.textBaseline = 'middle';
    g.fillStyle = tok('signature', '#fff');
    g.font = '900 ' + Math.round(26 * u) + 'px ' + DISPLAY;
    g.fillText((brand && brand.mark && brand.mark.wordmark) || '', pad + markW, base - Math.round(29 * u));
    g.textAlign = 'right';
    g.font = '600 ' + Math.round(21 * u) + 'px ' + BODY;
    g.fillStyle = tok('tag', '#ff6fb5');
    g.fillText(state.tag, S.w - pad, base - Math.round(29 * u));
    g.textAlign = 'left';
    g.textBaseline = 'top';
  }

  /* Paint one post onto any surface. The preview is one caller; saving all
     three sizes at once is another, and a second brand would be a third. The
     size is an argument rather than read from the page, which is the whole
     reason a post can be produced at a size nobody is currently looking at. */
  /* A template is a background and a list of blocks, and both come from the
     brand file. The vocabulary is deliberately small and closed — figure, rule,
     heading, body, chip, quote mark, attribution — because a general layout
     language would be a worse CSS that nobody can debug, while seven named
     blocks describe every template here and leave room for the next one.

     Each block says which field it draws, which colour role it wears, and at
     most what share of the space still left it may take. Sizing against what
     remains rather than a fraction of the canvas is what stops a long sentence
     running under the signature. */
  function paint(g, S) {
    if (!brand) return;
    /* One unit of type per size, so the same template reads the same on a
       square as on a story instead of being retuned three times. */
    var u = Math.min(S.w, S.h) / 1080;
    var pad = Math.round(Math.min(S.w, S.h) * 0.085);
    var colW = S.w - pad * 2;
    var f = state.fields;
    var t = template(state.template);
    var wide = state.size === 'wide';

    g.clearRect(0, 0, S.w, S.h);
    g.textBaseline = 'top'; g.textAlign = 'left';

    var ground = grounds();
    var bg = g.createLinearGradient(0, 0, S.w, S.h);
    bg.addColorStop(0, ground[0]); bg.addColorStop(1, ground[1]);
    g.fillStyle = bg; g.fillRect(0, 0, S.w, S.h);

    /* Each template keeps its own picture. One shared slot meant switching from
       a woman to a venue left her face behind the venue's name. */
    var picture = t.imageField ? images[f[t.imageField]] : null;
    var mark = (brand.mark && brand.mark.image) ? images[brand.mark.image] : null;
    var footH = Math.round(104 * u);
    var safeB = S.h - pad - footH;
    var boxW = colW;
    var y = pad;

    var bgSpec = t.background;
    if (bgSpec && picture) {
      if (bgSpec.fit === 'full') {
        photo(g, picture, 0, 0, S.w, S.h, !!bgSpec.duotone);
        scrim(g, 0, 0, S.w, S.h, 'rgba(0,0,0,0.5)', 'rgba(0,0,0,0.93)');
      } else if (wide && bgSpec.wide === 'side') {
        /* Landscape has width and no height: the picture takes the right of the
           frame and the words the left, rather than both fighting for the middle. */
        photo(g, picture, S.w * 0.42, 0, S.w * 0.58, S.h, !!bgSpec.duotone);
        var side = g.createLinearGradient(0, 0, S.w, 0);
        side.addColorStop(0, ground[0]); side.addColorStop(0.6, ground[0]);
        side.addColorStop(1, 'rgba(0,0,0,0)');
        g.fillStyle = side; g.fillRect(0, 0, S.w, S.h);
        boxW = Math.round(colW * 0.5);
      } else {
        var ph = Math.round(S.h * (bgSpec.height || 0.68));
        photo(g, picture, 0, 0, S.w, ph, !!bgSpec.duotone);
        scrim(g, 0, ph - Math.round(340 * u), S.w, Math.round(340 * u),
              'rgba(0,0,0,0)', ground[0]);
      }
    }

    /* Where the words start. A template with a picture behind them begins lower
       down, so they sit in the part of it the scrim has darkened. */
    var startAt = t.start;
    if (typeof startAt === 'object' && startAt) startAt = startAt[state.size] || startAt.other;
    if (typeof startAt === 'number') y = Math.round(S.h * startAt);
    else if (bgSpec && bgSpec.fit !== 'full' && !(wide && bgSpec.wide === 'side')) {
      y = Math.round(S.h * (bgSpec.height || 0.68)) - Math.round(200 * u);
    }
    if (wide && bgSpec && bgSpec.wide === 'side') y = Math.round(S.h * 0.28);

    var room = function () { return Math.max(0, safeB - y); };

    (t.blocks || []).forEach(function (block) {
      var text = block.from ? f[block.from] : block.text;
      if (block.from && !String(text || '').trim()) return;
      var colour = tok(block.colour || 'heading', '#ffffff');
      var take = block.take == null ? 1 : block.take;

      if (block.type === 'figure') {
        var num = String(text || '');
        g.font = '900 ' + Math.round(400 * u) + 'px ' + DISPLAY;
        var size = Math.round(Math.min(
          400 * u * Math.min(1, (boxW * 0.95) / g.measureText(num).width),
          room() * take
        ));
        g.font = '900 ' + size + 'px ' + DISPLAY;
        g.fillStyle = colour;
        g.fillText(num, pad, y);
        y += size * 0.97;
        return;
      }

      if (block.type === 'rule') {
        g.fillStyle = colour;
        g.fillRect(pad, y + Math.round(16 * u), Math.round((block.width || 150) * u),
                   Math.round((block.height || 10) * u));
        y += Math.round(58 * u);
        return;
      }

      if (block.type === 'chip') {
        var label = String(text || '').toUpperCase();
        g.font = '800 ' + Math.round(24 * u) + 'px ' + DISPLAY;
        var sw = g.measureText(label).width;
        var chipH = Math.round(56 * u), px = Math.round(26 * u);
        g.fillStyle = tok(block.colour || 'chip', '#d2246f');
        if (g.roundRect) { g.beginPath(); g.roundRect(pad, y, sw + px * 2, chipH, chipH / 2); g.fill(); }
        else g.fillRect(pad, y, sw + px * 2, chipH);
        g.fillStyle = tok('heading', '#fff');
        g.textBaseline = 'middle';
        g.fillText(label, pad + px, y + chipH / 2);
        g.textBaseline = 'top';
        y += chipH + Math.round(38 * u);
        return;
      }

      if (block.type === 'quoteMark') {
        g.font = '900 ' + Math.round(190 * u) + 'px ' + DISPLAY;
        g.fillStyle = colour;
        g.fillText('“', pad - Math.round(12 * u), y - Math.round(46 * u));
        y += Math.round(105 * u);
        return;
      }

      if (block.type === 'attribution') {
        g.font = '600 ' + Math.round((block.size || 32) * u) + 'px ' + BODY;
        g.fillStyle = colour;
        g.fillText('— ' + text, pad, y);
        y += Math.round((block.size || 32) * u * 1.5);
        return;
      }

      // heading and body: display or body face, fitted to what is left
      var isHeading = block.type === 'heading';
      var face = isHeading ? DISPLAY : BODY;
      var weight = block.weight || (isHeading ? '900' : '400');
      var blk = fit(g, text, boxW, room() * take, weight, face,
                    Math.round((block.size || (isHeading ? 96 : 40)) * u),
                    Math.round((block.min || (isHeading ? 30 : 18)) * u),
                    block.lh || (isHeading ? 1.06 : 1.4));
      y = draw(g, blk, pad, y, colour) + Math.round((block.after == null ? 24 : block.after) * u);
    });

    footer(g, S, u, pad, mark);
  }

  /* Draw the post the page is showing. */
  function render() {
    var S = SIZES[state.size];
    canvas.width = S.w; canvas.height = S.h;
    paint(ctx, S);
    dimsEl.textContent = S.w + ' × ' + S.h + ' · ' + S.note;
    countWords();
  }

  /* Draw it at a size nobody is looking at. This is the point of paint taking
     its surface: one post, every shape it needs to exist in, without the
     preview flickering through them. */
  function renderTo(key) {
    var S = SIZES[key];
    var off = document.createElement('canvas');
    off.width = S.w; off.height = S.h;
    var was = state.size;
    state.size = key;
    paint(off.getContext('2d'), S);
    state.size = was;
    return off;
  }

  function saveCanvas(cv, name) {
    return new Promise(function (resolve) {
      cv.toBlob(function (blob) {
        var url = URL.createObjectURL(blob);
        var a = document.createElement('a');
        a.href = url; a.download = name;
        document.body.appendChild(a); a.click(); a.remove();
        window.setTimeout(function () { URL.revokeObjectURL(url); resolve(); }, 400);
      }, 'image/png');
    });
  }


  /* What each platform will actually show before it cuts the caption off. */
  var LIMITS = { square: 125, story: 125, wide: 280 };
  function countWords() {
    var el = document.getElementById('caption-count');
    if (!el) return;
    var n = caption().length;
    var lim = LIMITS[state.size] || 280;
    el.textContent = n + ' characters · ' + (n <= lim
      ? 'shows in full'
      : 'cut off after about ' + lim + ' on this platform');
    el.className = 'note' + (n > lim ? ' warn' : '');
  }

  /* --- Controls ------------------------------------------------------------- */

  function chips(host, entries, current, pick) {
    host.innerHTML = '';
    entries.forEach(function (e) {
      var b = document.createElement('button');
      b.type = 'button'; b.className = 'chip'; b.textContent = e.label;
      b.setAttribute('aria-pressed', String(e.key === current));
      b.addEventListener('click', function () { pick(e.key); });
      host.appendChild(b);
    });
  }
  function entriesOf(obj, labelOf) {
    return Object.keys(obj).map(function (k) { return { key: k, label: labelOf(k) }; });
  }
  function paintTemplates() {
    chips(document.getElementById('templates'),
      templates().map(function (t) { return { key: t.key, label: t.label }; }),
      state.template, chooseTemplate);
  }
  function paintSizes() {
    chips(document.getElementById('sizes'),
      entriesOf(SIZES, function (k) { return SIZES[k].label; }),
      state.size, chooseSize);
  }
  function chooseTemplate(k) {
    state.template = k; paintTemplates(); buildFields();
    var t = template(k);
    load(t.imageField ? state.fields[t.imageField] : '').then(render);
  }
  function chooseSize(k) { state.size = k; paintSizes(); render(); }

  function field(host, id, label, value, type, options) {
    var l = document.createElement('label'); l.htmlFor = id; l.textContent = label;
    var el;
    if (type === 'select') {
      el = document.createElement('select');
      options.forEach(function (o) {
        var op = document.createElement('option');
        op.value = o.value; op.textContent = o.label; el.appendChild(op);
      });
    } else if (type === 'textarea') { el = document.createElement('textarea'); }
    else { el = document.createElement('input'); el.type = 'text'; }
    el.id = id;
    el.value = value == null ? '' : value;
    host.appendChild(l); host.appendChild(el);
    return el;
  }
  function bind(el, key) {
    var go = function () { state.fields[key] = el.value; render(); };
    el.addEventListener('input', go);
    el.addEventListener('change', go);
    return el;
  }

  function library(key) {
    var t = template(key);
    return (t.library && brand.libraries && brand.libraries[t.library]) || [];
  }

  function buildFields() {
    var host = document.getElementById('fields');
    host.innerHTML = '<legend>Words</legend>';
    var f = state.fields;
    var key = state.template;
    var lib = library(key);
    var t = template(key);

    /* A template that draws from a library gets its picker first, and choosing
       an entry fills the fields that entry carries. Which fields those are is
       the library's business, not the studio's. */
    if (lib.length) {
      var pick = field(host, 'f-pick', label(key, 'pick', 'Choose'), f[t.imageField],
        'select', lib.map(function (e) { return { value: e.image, label: e.label }; }));
      pick.addEventListener('change', function () {
        var entry = lib.filter(function (e) { return e.image === pick.value; })[0];
        if (!entry) return;
        state.fields[t.imageField] = entry.image;
        if (entry.fields) {
          Object.keys(entry.fields).forEach(function (k) {
            state.fields[k] = entry.fields[k];
            var el = document.getElementById('f-' + k);
            if (el) el.value = entry.fields[k];
          });
        }
        if (entry.label && document.getElementById('f-name')) {
          state.fields.name = entry.label;
          document.getElementById('f-name').value = entry.label;
        }
        load(entry.image).then(render);
      });
    }

    /* And the rest of the form is the template's own field list. A new
       template can declare a field this file has never heard of and it appears,
       which is the difference between templates as data and four layouts with
       their forms hard-coded beside them. */
    (t.fields || []).forEach(function (spec) {
      bind(field(host, 'f-' + spec.name, spec.label || spec.name,
                 f[spec.name], spec.type || 'text'), spec.name);
    });
  }

  /* Opening values come from the brand: every template says what it starts
     with, so the first thing anybody sees is a usable post rather than a form. */
  function defaults() {
    var fields = {};
    templates().forEach(function (t) {
      Object.keys(t.defaults || {}).forEach(function (k) { fields[k] = t.defaults[k]; });
      var lib = (t.library && brand.libraries && brand.libraries[t.library]) || [];
      if (lib.length && t.imageField) {
        fields[t.imageField] = lib[0].image;
        if (lib[0].fields) {
          Object.keys(lib[0].fields).forEach(function (k) {
            if (fields[k] == null) fields[k] = lib[0].fields[k];
          });
        }
        if (t.key === 'person' && fields.name == null) fields.name = lib[0].label;
      }
    });
    state.fields = fields;
  }

  /* {field} in a pattern is replaced by what is in that field; a pattern with
     nothing in it disappears rather than leaving a stray dash. Both the caption
     and the alt text are written this way, in the brand file, because both are
     the brand's words and not this file's. */
  function fill(pattern) {
    if (!pattern) return '';
    return String(pattern)
      .replace(/\{([a-z0-9_]+)\}/gi, function (_, key) {
        if (key === 'site') return (brand && brand.site) || '';
        if (key === 'brand') return (brand && brand.name) || '';
        return state.fields[key] == null ? '' : String(state.fields[key]);
      })
      .replace(/\s*·\s*(·\s*)+/g, ' · ')
      .replace(/^[\s·—-]+|[\s·—-]+$/g, '')
      .replace(/[ 	]{2,}/g, ' ')
      .trim();
  }

  function caption() {
    var t = template(state.template);
    var body = fill(t.caption);
    var site = (brand && brand.site) || '';
    return [body, '', site, state.tag].filter(function (x, i) {
      return x !== '' || i === 1;
    }).join('\n');
  }

  /* Alt text describes what is on the canvas. It is the half of a post that
     gets left blank, because it is normally written separately and nobody is
     holding the picture at the time. */
  function altText() {
    return fill(template(state.template).alt);
  }

  function say(msg) {
    statusEl.textContent = msg;
    window.setTimeout(function () { statusEl.innerHTML = '&nbsp;'; }, 2600);
  }

  function filename() {
    var t = template(state.template);
    var stem = (t.stem && state.fields[t.stem]) || t.key || 'post';
    return ((brand && brand.id) || 'post') + '-' + stem.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
      + '-' + state.size + '.png';
  }

  function start() {
    paintTemplates();
    paintSizes();

    var tagSel = document.getElementById('tag');
    tagSel.innerHTML = '';
    (brand.tags || []).forEach(function (t) {
      var o = document.createElement('option'); o.value = t; o.textContent = t; tagSel.appendChild(o);
    });
    tagSel.value = state.tag;

    /* The grounds are the brand's too. They were three fixed options in the
       markup, which is exactly the sort of thing that makes a tool single-
       tenant without anybody noticing. */
    var groundSel = document.getElementById('ground');
    groundSel.innerHTML = '';
    (brand.grounds || []).forEach(function (gr) {
      var o = document.createElement('option'); o.value = gr.key; o.textContent = gr.label;
      groundSel.appendChild(o);
    });
    groundSel.value = state.ground;
    tagSel.addEventListener('change', function () { state.tag = tagSel.value; render(); });

    document.getElementById('ground').addEventListener('change', function (e) {
      state.ground = e.target.value; render();
    });

    document.getElementById('download').addEventListener('click', function () {
      canvas.toBlob(function (blob) {
        var url = URL.createObjectURL(blob);
        var a = document.createElement('a');
        a.href = url; a.download = filename();
        document.body.appendChild(a); a.click(); a.remove();
        window.setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
        say('Saved ' + filename());
      }, 'image/png');
    });

    document.getElementById('copy').addEventListener('click', function () {
      if (navigator.clipboard) {
        navigator.clipboard.writeText(caption()).then(function () { say('Caption copied'); });
      } else {
        say('Copy is not available in this browser');
      }
    });

    document.getElementById('copy-alt').addEventListener('click', function () {
      if (navigator.clipboard) {
        navigator.clipboard.writeText(altText()).then(function () { say('Alt text copied'); });
      } else {
        say('Copy is not available in this browser');
      }
    });

    /* Every shape at once. A volunteer posting the same thing to the feed, to
       stories and to X should not have to find this page three times. */
    document.getElementById('download-all').addEventListener('click', async function () {
      var keys = Object.keys(SIZES);
      say('Saving ' + keys.length + ' sizes…');
      for (var i = 0; i < keys.length; i++) {
        var was = state.size;
        state.size = keys[i];
        var name = filename();
        state.size = was;
        await saveCanvas(renderTo(keys[i]), name);
      }
      say('Saved all ' + keys.length);
    });

    /* Any photograph, not only the ones the site already has. */
    var picker = document.getElementById('own-image');
    if (picker) {
      picker.addEventListener('change', function () {
        var file = picker.files && picker.files[0];
        if (!file) return;
        var url = URL.createObjectURL(file);
        var key = template(state.template).imageField;
        if (!key) { say('This template does not use a picture'); return; }
        load(url).then(function (img) {
          if (!img) { say('That file could not be read as a picture'); return; }
          state.fields[key] = url;
          render();
          say('Using your picture');
        });
      });
    }

    buildFields();
    /* Whatever this brand actually has: its badge if it has one, and the first
       entry of every library it declares. */
    var want = [];
    if (brand.mark && brand.mark.image) want.push(brand.mark.image);
    templates().forEach(function (t) {
      if (t.imageField && state.fields[t.imageField]) want.push(state.fields[t.imageField]);
    });
    Promise.all(want.map(load)).then(render);
  }

  /* Which brand to draw. One studio, any number of these. */
  function brandId() {
    var q = new URLSearchParams(location.search).get('brand');
    return (q || 'metupuk').replace(/[^a-z0-9-]/gi, '');
  }

  function openBrand(id) {
    return fetch('/social/brands/' + id + '.json')
      .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
      .then(function (b) {
        brand = b;
        DISPLAY = (b.type && b.type.display) || DISPLAY;
        BODY = (b.type && b.type.body) || BODY;
        DUOTONE = b.duotone || DUOTONE;
        state.template = (b.templates && b.templates[0] && b.templates[0].key) || 'figure';
        state.ground = (b.grounds && b.grounds[0] && b.grounds[0].key) || '';
        state.tag = (b.tags && b.tags[0]) || '';
        document.title = 'Social templates — ' + b.name;
        /* A brand brings its own typefaces with it. */
        if (b.type && b.type.webfonts) {
          var link = document.createElement('link');
          link.rel = 'stylesheet'; link.href = b.type.webfonts;
          document.head.appendChild(link);
        }
        defaults();
        /* The brand's typefaces must be in memory before anything is drawn:
           canvas does not wait for a webfont, it draws in whatever it has, and
           the export is quietly in the wrong face while the page looks right. */
        var need = (b.type && b.type.preload) || [];
        return (document.fonts
          ? Promise.all(need.map(function (n) {
              return document.fonts.load(n).catch(function () { /* fall back */ });
            }))
          : Promise.resolve());
      });
  }

  openBrand(brandId())
    .then(start)
    .catch(function () {
      statusEl.textContent = 'Could not open the brand file for “' + brandId()
        + '”. Run the build, or check /social/brands/.';
    });
}());
