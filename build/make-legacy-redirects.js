// Write the redirect rules for the WordPress taxonomy URLs.
//
//   node build/make-legacy-redirects.js
//
// The live site's sitemap carries 420 URLs the rebuild has no equivalent for:
// 22 /category/, 380 /tag/, 18 /author/. They are indexed, and every post on
// the current site links to some of them, so on the day this replaces the live
// site they all become 404s unless something catches them.
//
// Most of them can go somewhere true rather than somewhere generic:
//   - 21 of the 22 categories are our topic routes under a different name
//   - 10 tags happen to share a slug with one of those topics
//   - 7 of the 18 authors have a page of their own on this site
//
// The rest fall to the news index, which is the honest answer: their content is
// there, just not filed that way any more.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LEGACY = path.join(ROOT, '_legacy');
const REDIRECTS = path.join(ROOT, 'src', 'static', '_redirects');
const NEWS = '/latest-news/';

const slugsFrom = (file) => [...fs.readFileSync(path.join(LEGACY, file), 'utf8')
  .matchAll(/<loc>([^<]+)<\/loc>/g)]
  .map((m) => m[1].replace(/^https?:\/\/[^/]+/, '').split('/').filter(Boolean).pop())
  .filter(Boolean);

function sitePages() {
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const f = path.join(d, e.name);
      if (e.isDirectory()) walk(f);
      else if (e.name === 'index.html') {
        const parts = path.relative(path.join(ROOT, 'dist'), f).split(path.sep).slice(0, -1);
        if (parts.length) out.push('/' + parts.join('/') + '/');
      }
    }
  };
  walk(path.join(ROOT, 'dist'));
  return out;
}

function main() {
  const topics = fs.readdirSync(path.join(ROOT, 'dist', 'news', 'topic'));
  const pages = sitePages();
  const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z]/g, '');

  const lines = [];
  const rule = (from, to) => lines.push(`${from.padEnd(46)}${to.padEnd(42)}301`);

  lines.push('# --- WordPress taxonomy URLs -------------------------------------------');
  lines.push('# 420 addresses in the live sitemap that this site has no equivalent for.');
  lines.push('# Generated by build/make-legacy-redirects.js from the live sitemaps.');
  lines.push('');
  lines.push('# Categories are our topics under an older name. uncategorized is the one');
  lines.push('# with nothing to point at, so it goes first — these are read in order.');
  rule('/category/uncategorized/*', NEWS);
  rule('/category/:slug/*', '/news/topic/:slug/');
  rule('/category/*', NEWS);
  lines.push('');

  const tags = slugsFrom('post_tag.xml');
  const tagHits = tags.filter((t) => topics.includes(t)).sort();
  lines.push(`# ${tagHits.length} of the ${tags.length} tags share a slug with a topic and can land on it.`);
  tagHits.forEach((t) => rule(`/tag/${t}/*`, `/news/topic/${t}/`));
  lines.push('# The rest were only ever a filing system; their posts are all still here.');
  rule('/tag/*', NEWS);
  lines.push('');

  const authors = slugsFrom('author.xml');
  const authorHits = [];
  for (const a of authors) {
    const hit = pages.find((u) => norm(u.split('/').filter(Boolean).pop()) === norm(a));
    if (hit) authorHits.push([a, hit]);
  }
  lines.push(`# ${authorHits.length} of the ${authors.length} authors have a page here — better than an index.`);
  authorHits.forEach(([a, u]) => rule(`/author/${a}/*`, u));
  rule('/author/*', NEWS);
  lines.push('');

  const block = lines.join('\n');

  let current = fs.readFileSync(REDIRECTS, 'utf8');
  const eol = current.includes('\r\n') ? '\r\n' : '\n';
  const marker = '# Serve the custom 404 for anything that does not resolve.';
  if (!current.includes(marker)) throw new Error('404 rule not found — refusing to guess where to insert');

  // Strip a previous run so this is repeatable.
  current = current.replace(/# --- WordPress taxonomy URLs[\s\S]*?(?=# Serve the custom 404)/, '');
  current = current.replace(marker, block.split('\n').join(eol) + eol + marker);
  fs.writeFileSync(REDIRECTS, current);

  const total = 3 + tagHits.length + 1 + authorHits.length + 1;
  console.log(`  ${total} rules written, covering ${22 + tags.length + authors.length} legacy URLs`);
  console.log(`    categories  21 to their topic, 1 to the news index`);
  console.log(`    tags        ${tagHits.length} to a topic, ${tags.length - tagHits.length} to the news index`);
  console.log(`    authors     ${authorHits.length} to their own page, ${authors.length - authorHits.length} to the news index`);
}

main();
